import { readFileSync, writeFileSync } from "node:fs";

const out = new URL("../../contracts/out/", import.meta.url);
const read = (path) => JSON.parse(readFileSync(new URL(path, out), "utf8")).abi;

const contents = `// Generated by scripts/abi.mjs from the Foundry build. Don't edit by hand.
export const firstrowAbi = ${JSON.stringify(read("Firstrow.sol/Firstrow.json"), null, 2)} as const;

export const forwarderAbi = ${JSON.stringify(read("ERC2771Forwarder.sol/ERC2771Forwarder.json"), null, 2)} as const;
`;

writeFileSync(new URL("../src/lib/abi.ts", import.meta.url), contents);
console.log("wrote src/lib/abi.ts");
